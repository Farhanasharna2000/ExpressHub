// Builds testing/reports/test-inventory.md from the real test files, so the inventory can
// never drift from what exists. Run from the repository root: node testing/tools/build-test-inventory.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SUITES = [
  { dir: "tests", match: /\.test\.mjs$/, kind: "Unit", how: "npm test" },
  { dir: "tests", match: /\.integration\.mjs$/, kind: "Integration", how: "npm run test:<name>:integration (needs Postgres)" },
  { dir: "tests/browser", match: /\.spec\.ts$/, kind: "Browser (mocked API)", how: "npm run test:frontend:browser" },
  { dir: "tests/e2e", match: /\.spec\.ts$/, kind: "Full-stack E2E", how: "npm run test:e2e (needs Postgres)" },
];

const titleOf = (line) => {
  const m = /^\s*(?:test|it)(?:\.\w+)?\(\s*(`[^`]*`|"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')/.exec(line);
  return m ? m[1].slice(1, -1).replace(/\\"/g, '"') : null;
};

const rows = [];
for (const suite of SUITES) {
  for (const file of readdirSync(suite.dir).filter((name) => suite.match.test(name)).sort()) {
    const path = `${suite.dir}/${file}`;
    const titles = readFileSync(path, "utf8").split("\n").map(titleOf).filter(Boolean);
    rows.push({ ...suite, path, titles });
  }
}

const esc = (text) => text.replace(/\|/g, "\\|");
let out = "# Test inventory\n\n";
out += "Generated by `testing/tools/build-test-inventory.mjs` from the test files. Do not edit by hand.\n";
out += "Integration files hold one scripted scenario each and print a summary line, so they show as one entry.\n\n";
out += "| Layer | Files | Test titles |\n|---|---|---|\n";
for (const kind of [...new Set(SUITES.map((s) => s.kind))]) {
  const group = rows.filter((r) => r.kind === kind);
  out += `| ${kind} | ${group.length} | ${group.reduce((n, r) => n + (r.kind === "Integration" ? 1 : r.titles.length), 0)} |\n`;
}
for (const row of rows) {
  out += `\n## ${row.kind}: \`${row.path}\`\n\nRun: \`${row.how}\`\n\n`;
  if (row.kind === "Integration") { out += "One scripted scenario (see the summary line it prints).\n"; continue; }
  row.titles.forEach((title, index) => { out += `${index + 1}. ${esc(title)}\n`; });
}
writeFileSync("testing/reports/test-inventory.md", out);
console.log(rows.map((r) => `${r.kind}\t${r.path}\t${r.titles.length}`).join("\n"));
